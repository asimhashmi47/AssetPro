    private async Task LoadContextAsync()
    {
        _adminId = await db.Users.Where(u => u.Role == UserRole.Admin).Select(u => u.Id).FirstAsync();
        _types.AddRange(await db.AssetTypes.ToListAsync());
        _brands.AddRange(await db.Brands.ToListAsync());
        _locations.AddRange(await db.Locations.ToListAsync());

        foreach (var prefix in _types.Select(t => t.TagPrefix).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            var tags = await db.Assets.Where(a => a.AssetTag.StartsWith(prefix + "-")).Select(a => a.AssetTag).ToListAsync();
            _tagCounters[prefix] = tags.Select(t => int.TryParse(t[(prefix.Length + 1)..], out var n) ? n : 0).DefaultIfEmpty(0).Max();
        }

        var numbers = await db.Requests.Select(r => r.RequestNumber).ToListAsync();
        _requestCounter = numbers.Select(n => int.TryParse(n.Replace("REQ-", ""), out var x) ? x : 0).DefaultIfEmpty(0).Max();
        _employeeCounter = (await db.Employees.Select(e => e.EmployeeCode).ToListAsync())
            .Select(c => int.TryParse(c.Replace("EMP-", ""), out var x) ? x : 0).DefaultIfEmpty(0).Max();
        _serialCounter = await db.Assets.CountAsync() + 1000;

        // Existing stock levels per item, so BalanceAfter stays truthful for items shared with the core seed.
        foreach (var row in await db.InventoryItems.Select(i => new { i.Id, InStock = i.Assets.Count(a => a.Status == AssetStatus.InStock) }).ToListAsync())
            _inStockPerItem[row.Id] = row.InStock;

        await BuildCatalogAsync();
    }

