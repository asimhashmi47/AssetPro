    private async Task<bool> MaybeStockInAsync(DateTime at)
    {
        // Roughly two deliveries a week, and never when the shelves are already full.
        if (_rng.Next(0, 3) != 0) return false;
        if (_assets.Count(a => a.Status == AssetStatus.InStock) > 110) return false;
        await StockInAsync(at, initial: false);
        return true;
    }

    private async Task StockInAsync(DateTime at, bool initial)
    {
        var picks = initial ? _catalog.OrderBy(_ => _rng.Next()).Take(12).ToList() : [_catalog[_rng.Next(_catalog.Count)]];
        foreach (var entry in picks)
        {
            var quantity = initial ? _rng.Next(6, 14) : _rng.Next(2, 9);
            var purchase = DateOnly.FromDateTime(at.AddDays(-_rng.Next(3, 20)));
            var location = _locations.First(l => l.Name == "IT Store Room");
            var created = new List<Asset>();

            for (var i = 0; i < quantity; i++)
            {
                var type = _types.First(t => t.Id == entry.Item.AssetTypeId);
                _tagCounters[type.TagPrefix] = _tagCounters.GetValueOrDefault(type.TagPrefix) + 1;
                var asset = new Asset
                {
                    AssetTag = $"{type.TagPrefix}-{_tagCounters[type.TagPrefix]:D5}",
                    Name = entry.Item.Name,
                    AssetTypeId = entry.Item.AssetTypeId,
                    BrandId = entry.Item.BrandId,
                    Model = entry.Item.Model,
                    SerialNumber = entry.HasSerial ? $"SN{++_serialCounter:D7}" : null,
                    PurchaseDate = purchase,
                    PurchaseCost = entry.UnitCost,
                    WarrantyExpiry = entry.UnitCost < 50 ? null : purchase.AddYears(entry.UnitCost < 200 ? 1 : 3),
                    Condition = AssetCondition.New,
                    Status = AssetStatus.InStock,
                    LocationId = location.Id,
                    InventoryItemId = entry.Item.Id,
                    CreatedAt = at,
                    UpdatedAt = at
                };
                db.Assets.Add(asset);
                created.Add(asset);
                _assets.Add(asset);
            }
            await db.SaveChangesAsync();

            foreach (var asset in created)
                History(asset, AssetAction.StockIn, null, AssetStatus.InStock, null, "Received into inventory", at);

            _inStockPerItem[entry.Item.Id] = _inStockPerItem.GetValueOrDefault(entry.Item.Id) + quantity;
            Txn(entry.Item.Id, InventoryTransactionType.StockIn, quantity, entry.Item.Id, null, null,
                $"Purchase order received ({created[0].AssetTag} – {created[^1].AssetTag})", at);
            Activity(ActivityActions.InventoryAdded, $"Stocked in {quantity} × {entry.Item.Name}", "InventoryItem", entry.Item.Id, at);
        }
    }

    private bool Assign(DateTime at)
    {
        var asset = Pick(_assets.Where(a => a.Status == AssetStatus.InStock));
        if (asset is null) return false;

        // Prefer someone who holds little, so assets spread across the company.
        var load = _openAssignments.Values.GroupBy(a => a.EmployeeId).ToDictionary(g => g.Key, g => g.Count());
        var employee = _staff.OrderBy(e => load.GetValueOrDefault(e.Id)).ThenBy(_ => _rng.Next()).First();

        db.AssetAssignments.Add(new AssetAssignment
        {
            AssetId = asset.Id, EmployeeId = employee.Id, AssignedById = _adminId, AssignedAt = at,
            ConditionAtAssignment = asset.Condition,
            Notes = _rng.Next(0, 3) == 0 ? "Issued with charger and carry case" : null
        });
        asset.Status = AssetStatus.Assigned;
        asset.UpdatedAt = at;
        History(asset, AssetAction.Assigned, AssetStatus.InStock, AssetStatus.Assigned, employee.Id, $"Assigned to {employee.FullName}", at);
        Consume(asset, InventoryTransactionType.StockOut, 1, asset.Id, employee.Id, $"Assigned to {employee.FullName}", at);
        Activity(ActivityActions.AssetAssigned, $"Assigned {asset.AssetTag} to {employee.FullName}", "Asset", asset.Id, at);
        return true;
    }

    private bool Return(DateTime at)
    {
        // Only hand back things that have been out for a while.
        var candidates = _openAssignments.Values.Where(a => a.AssignedAt < at.AddDays(-25)).ToList();
        if (candidates.Count == 0) return false;
        var assignment = candidates[_rng.Next(candidates.Count)];
        var asset = _assets.First(a => a.Id == assignment.AssetId);
        var employee = _staff.First(e => e.Id == assignment.EmployeeId);

        var roll = _rng.Next(0, 100);
        var (condition, status) = roll switch
        {
            < 55 => (AssetCondition.Good, AssetStatus.InStock),
            < 75 => (AssetCondition.Fair, AssetStatus.InStock),
            < 88 => (AssetCondition.Damaged, AssetStatus.UnderRepair),
            < 96 => (AssetCondition.Damaged, AssetStatus.Damaged),
            _ => (AssetCondition.Critical, AssetStatus.Scrapped)
        };
        var damage = condition is AssetCondition.Damaged or AssetCondition.Critical
            ? Pick(["Screen cracked", "Battery no longer charges", "Liquid damage", "Hinge broken", "Fan rattling loudly", "Port not working"])
            : null;

        assignment.ReturnedAt = at;
        assignment.ReturnedBy = employee.FullName;
        assignment.ReceivedById = _adminId;
        assignment.ReturnCondition = condition;
        assignment.DamageDetails = damage;
        assignment.ReturnNotes = status == AssetStatus.InStock ? "Checked and cleaned, back on the shelf" : damage;
        _openAssignments.Remove(asset.Id);

        asset.Condition = condition;
        asset.Status = status;
        asset.UpdatedAt = at;
        History(asset, AssetAction.Returned, AssetStatus.Assigned, status, employee.Id,
            damage is null ? $"Returned by {employee.FullName}" : $"Returned by {employee.FullName} – {damage}", at);

        switch (status)
        {
            case AssetStatus.InStock:
                Restock(asset, InventoryTransactionType.Return, employee.Id, $"Returned by {employee.FullName}", at);
                break;
            case AssetStatus.UnderRepair:
                History(asset, AssetAction.RepairStarted, AssetStatus.UnderRepair, AssetStatus.UnderRepair, null, "Sent to repair after return", at);
                break;
            case AssetStatus.Damaged:
                History(asset, AssetAction.Damaged, AssetStatus.Damaged, AssetStatus.Damaged, null, damage ?? "Marked damaged on return", at);
                break;
            case AssetStatus.Scrapped:
                ScrapRecordFor(asset, damage ?? "Beyond economical repair", at, wasInStock: false);
                break;
        }
        Activity(ActivityActions.AssetReturned, $"{asset.AssetTag} returned by {employee.FullName} ({status})", "Asset", asset.Id, at);
        return true;
    }

    private bool RepairStart(DateTime at)
    {
        var asset = Pick(_assets.Where(a => a.Status is AssetStatus.InStock or AssetStatus.Damaged && a.UpdatedAt < at.AddDays(-3)));
        if (asset is null) return false;
        var previous = asset.Status;
        var note = Pick(["Keyboard backlight failing", "Overheating under load", "Battery health below 60%", "Display flickering",
            "USB ports intermittent", "Loud fan noise", "Touchpad unresponsive"])!;

        asset.Status = AssetStatus.UnderRepair;
        asset.UpdatedAt = at;
        History(asset, AssetAction.RepairStarted, previous, AssetStatus.UnderRepair, Holder(asset), note, at);
        if (previous == AssetStatus.InStock) Consume(asset, InventoryTransactionType.Adjustment, -1, asset.Id, null, "Sent to repair", at);
        Activity(ActivityActions.AssetRepaired, $"Repair started for {asset.AssetTag}", "Asset", asset.Id, at);
        return true;
    }

    private bool RepairComplete(DateTime at)
    {
        var asset = Pick(_assets.Where(a => a.Status == AssetStatus.UnderRepair && a.UpdatedAt < at.AddDays(-4)));
        if (asset is null) return false;
        var holder = Holder(asset);
        var stillAssigned = holder is not null;

        asset.Status = stillAssigned ? AssetStatus.Assigned : AssetStatus.InStock;
        asset.Condition = _rng.Next(0, 4) == 0 ? AssetCondition.Fair : AssetCondition.Good;
        asset.UpdatedAt = at;
        History(asset, AssetAction.RepairCompleted, AssetStatus.UnderRepair, asset.Status, holder,
            Pick(["Repaired under warranty", "Part replaced by the service centre", "Cleaned and re-pasted, temperatures normal",
                "Firmware updated and tested"]), at);
        if (!stillAssigned) Restock(asset, InventoryTransactionType.Adjustment, null, "Repaired and released to stock", at);
        Activity(ActivityActions.AssetRepaired, $"Repair completed for {asset.AssetTag}", "Asset", asset.Id, at);
        return true;
    }

    private bool ReplaceComponent(DateTime at)
    {
        if (!Chance(45)) return false;
        var asset = Pick(_assets.Where(a => a.Status is AssetStatus.Assigned or AssetStatus.UnderRepair or AssetStatus.InStock));
        if (asset is null) return false;
        var entry = _catalog.FirstOrDefault(c => c.Item.Id == asset.InventoryItemId);
        var component = Pick(entry?.Components ?? ["RAM", "Battery", "Charger"])!;

        var (oldPart, newPart) = component switch
        {
            "RAM" => ("8GB DDR5", "16GB DDR5"),
            "SSD / Storage" => ("256GB NVMe", "512GB NVMe"),
            "Battery" => ("Original battery", "Replacement battery (OEM)"),
            "Screen" => ("Original panel", "Replacement panel (OEM)"),
            "Keyboard" => ("Original keyboard", "OEM backlit keyboard"),
            "Charger" => ("65W charger", "65W charger (replacement)"),
            _ => ($"Original {component.ToLowerInvariant()}", $"New {component.ToLowerInvariant()}")
        };
        var reason = Pick([$"{component} failure", "Worn out through daily use", "Upgrade requested by the employee",
            "Faulty on inspection", "Covered by warranty replacement"])!;

        db.ComponentReplacements.Add(new ComponentReplacement
        {
            AssetId = asset.Id, Component = component, OldComponent = oldPart, NewComponent = newPart, Reason = reason,
            ReplacedOn = DateOnly.FromDateTime(at), PerformedById = _adminId, CreatedAt = at,
            Notes = _rng.Next(0, 2) == 0 ? $"{component} replaced and tested." : null
        });
        History(asset, AssetAction.ComponentReplaced, asset.Status, asset.Status, Holder(asset),
            $"{component}: {oldPart} → {newPart} ({reason})", at);
        Activity(ActivityActions.ComponentReplaced, $"Replaced {component} on {asset.AssetTag}", "Asset", asset.Id, at);
        asset.UpdatedAt = at;
        return true;
    }

    private bool MarkDamaged(DateTime at)
    {
        if (!Chance(30)) return false;
        var asset = Pick(_assets.Where(a => a.Status == AssetStatus.InStock && a.UpdatedAt < at.AddDays(-10)));
        if (asset is null) return false;
        var note = Pick(["Dead pixels found during inspection", "Casing cracked in storage", "Will not power on", "Water damage found on inspection"])!;

        asset.Status = AssetStatus.Damaged;
        asset.Condition = AssetCondition.Damaged;
        asset.UpdatedAt = at;
        History(asset, AssetAction.Damaged, AssetStatus.InStock, AssetStatus.Damaged, null, note, at);
        Consume(asset, InventoryTransactionType.Adjustment, -1, asset.Id, null, note, at);
        Activity(ActivityActions.AssetStatusChanged, $"{asset.AssetTag}: InStock → Damaged", "Asset", asset.Id, at);
        return true;
    }

    private bool ReleaseToStock(DateTime at)
    {
        var asset = Pick(_assets.Where(a => a.Status == AssetStatus.Damaged && a.UpdatedAt < at.AddDays(-6)));
        if (asset is null) return false;

        asset.Status = AssetStatus.InStock;
        asset.Condition = AssetCondition.Fair;
        asset.UpdatedAt = at;
        History(asset, AssetAction.StatusChanged, AssetStatus.Damaged, AssetStatus.InStock, null, "Inspected and usable again – released to stock", at);
        Restock(asset, InventoryTransactionType.Adjustment, null, "Released to stock", at);
        Activity(ActivityActions.AssetStatusChanged, $"{asset.AssetTag}: Damaged → InStock", "Asset", asset.Id, at);
        return true;
    }

    private bool Retire(DateTime at)
    {
        if (!Chance(14)) return false;
        var asset = Pick(_assets.Where(a => a.Status is AssetStatus.InStock or AssetStatus.Damaged
            && a.PurchaseDate != null && a.PurchaseDate < DateOnly.FromDateTime(at.AddDays(-120))));
        if (asset is null) return false;
        var previous = asset.Status;

        asset.Status = AssetStatus.Retired;
        asset.UpdatedAt = at;
        History(asset, AssetAction.Retired, previous, AssetStatus.Retired, null,
            Pick(["End of life – replaced by newer hardware", "Retired after lease period", "Superseded by the current standard model"]), at);
        if (previous == AssetStatus.InStock) Consume(asset, InventoryTransactionType.Adjustment, -1, asset.Id, null, "Retired", at);
        Activity(ActivityActions.AssetStatusChanged, $"{asset.AssetTag}: {previous} → Retired", "Asset", asset.Id, at);
        return true;
    }

    private bool Scrap(DateTime at)
    {
        // Writing kit off is genuinely rare; without a gate the pool scraps a third of the estate.
        if (!Chance(14)) return false;
        var asset = Pick(_assets.Where(a => a.Status is AssetStatus.Damaged or AssetStatus.Retired or AssetStatus.UnderRepair
            && a.UpdatedAt < at.AddDays(-8)));
        if (asset is null) return false;
        var previous = asset.Status;
        var reason = Pick(["Not economical to repair", "Motherboard failure, beyond repair", "Liquid damage, written off",
            "Screen and chassis damaged beyond repair", "Battery swelling – unsafe to use"])!;

        asset.Status = AssetStatus.Scrapped;
        asset.UpdatedAt = at;
        History(asset, AssetAction.Scrapped, previous, AssetStatus.Scrapped, null, reason, at);
        ScrapRecordFor(asset, reason, at, wasInStock: false);
        Activity(ActivityActions.AssetScrapped, $"{asset.AssetTag} moved to scrap: {reason}", "Asset", asset.Id, at);
        return true;
    }

    private bool CreateRequest(DateTime at)
    {
        if (_requesters.Count == 0 || !Chance(35)) return false;
        var (userId, employeeId) = _requesters[_rng.Next(_requesters.Count)];
        var held = _openAssignments.Values.Where(a => a.EmployeeId == employeeId).ToList();

        RequestType type;
        int? assetId = null;
        string comment;
        if (held.Count > 0 && _rng.Next(0, 100) < 65)
        {
            var assignment = held[_rng.Next(held.Count)];
            var asset = _assets.First(a => a.Id == assignment.AssetId);
            // One open request per asset and type, same as the API allows.
            if (_liveRequests.Any(r => r.AssetId == asset.Id)) return false;
            assetId = asset.Id;
            type = Pick([RequestType.Repair, RequestType.Repair, RequestType.Replacement, RequestType.Return]);
            comment = type switch
            {
                RequestType.Repair => Pick(["The fan is very loud under load and it gets hot.", "Battery drains within two hours now.",
                    "Screen flickers when I move the lid.", "A few keys have stopped responding."])!,
                RequestType.Replacement => Pick(["The scroll wheel skips constantly, please replace it.", "Two keycaps are missing.",
                    "The headset cable is frayed near the plug."])!,
                _ => Pick(["I no longer need this, happy to hand it back.", "Switching to a laptop, returning the desktop."])!
            };
        }
        else
        {
            type = Pick([RequestType.NewAsset, RequestType.NewAsset, RequestType.Other]);
            comment = type == RequestType.NewAsset
                ? Pick(["Could I get a second monitor for reconciliation work?", "I need a headset for client calls.",
                    "Requesting a USB-C dock for the new laptop.", "A laptop stand would help with posture.",
                    "Please provide a tablet for site visits."])!
                : Pick(["Please update my laptop to the latest OS image.", "Can someone check my VPN setup?",
                    "Requesting an extra charger for the office."])!;
        }

        var request = new AssetRequest
        {
            RequestNumber = $"REQ-{++_requestCounter:D4}",
            Type = type,
            AssetId = assetId,
            RequesterEmployeeId = employeeId,
            RequesterUserId = userId,
            Comments = comment,
            Status = RequestStatus.Submitted,
            CreatedAt = at,
            UpdatedAt = at
        };
        request.StatusHistory.Add(new RequestStatusHistory
        {
            ToStatus = RequestStatus.Submitted, ChangedById = userId, ChangedAt = at, Note = "Request submitted"
        });
        db.Requests.Add(request);
        _liveRequests.Add(request);

        if (type == RequestType.Repair && assetId is not null)
        {
            var asset = _assets.First(a => a.Id == assetId);
            History(asset, AssetAction.RepairRequested, asset.Status, asset.Status, employeeId, $"{request.RequestNumber}: {comment}", at);
        }
        Activity(ActivityActions.RequestCreated, $"{request.RequestNumber} ({type}) submitted", "Request", null, at, userId);
        return true;
    }

    private bool AdvanceRequest(DateTime at)
    {
        var ready = _liveRequests.Where(r => r.UpdatedAt < at.AddHours(-16)).ToList();
        if (ready.Count == 0) return false;
        var request = ready[_rng.Next(ready.Count)];
        var requesterUserId = request.RequesterUserId;

        var (next, byUser, note) = request.Status switch
        {
            RequestStatus.Submitted when _rng.Next(0, 100) < 12 =>
                (RequestStatus.Rejected, _adminId, Pick(["Not covered by the equipment policy.", "Please use the ergonomic allowance for this.",
                    "Existing asset is still within its replacement cycle."])),
            RequestStatus.Submitted => (RequestStatus.Approved, _adminId, _rng.Next(0, 3) == 0 ? "Approved – stock available." : null),
            RequestStatus.Approved => (RequestStatus.InProgress, _adminId, Pick(["Ordering the part.", "Preparing the device.", null])),
            RequestStatus.InProgress => (RequestStatus.Delivered, _adminId, Pick(["Delivered to the desk.", "Handed over in person.", null])),
            RequestStatus.Delivered => (RequestStatus.Checking, requesterUserId, null),
            RequestStatus.Checking => (RequestStatus.Received, requesterUserId, _rng.Next(0, 2) == 0 ? "All good, thanks!" : null),
            _ => (RequestStatus.Done, _adminId, null)
        };

        db.RequestStatusHistory.Add(new RequestStatusHistory
        {
            RequestId = request.Id, FromStatus = request.Status, ToStatus = next, ChangedById = byUser, ChangedAt = at, Note = note
        });

        var activity = next switch
        {
            RequestStatus.Approved => ActivityActions.RequestApproved,
            RequestStatus.Rejected => ActivityActions.RequestRejected,
            _ => ActivityActions.RequestStatusChanged
        };
        Activity(activity, $"{request.RequestNumber}: {request.Status} → {next}", "Request", request.Id, at, byUser);

        // A delivered repair usually means the asset came back working.
        if (next == RequestStatus.Delivered && request.AssetId is { } assetId && request.Type == RequestType.Repair)
        {
            var asset = _assets.FirstOrDefault(a => a.Id == assetId);
            if (asset is { Status: AssetStatus.UnderRepair })
            {
                var holder = Holder(asset);
                asset.Status = holder is null ? AssetStatus.InStock : AssetStatus.Assigned;
                asset.Condition = AssetCondition.Good;
                asset.UpdatedAt = at;
                History(asset, AssetAction.RepairCompleted, AssetStatus.UnderRepair, asset.Status, holder, $"Repaired for {request.RequestNumber}", at);
                if (holder is null) Restock(asset, InventoryTransactionType.Adjustment, null, "Repaired and released to stock", at);
            }
        }

        request.Status = next;
        request.UpdatedAt = at;
        if (next is RequestStatus.Done or RequestStatus.Rejected) _liveRequests.Remove(request);
        return true;
    }

    private bool LogSignIn(DateTime at)
    {
        var (userId, _) = _requesters.Count > 0 && _rng.Next(0, 3) > 0 ? _requesters[_rng.Next(_requesters.Count)] : (_adminId, 0);
        Activity(ActivityActions.Login, "Signed in", "User", userId, at, userId);
        return true;
    }

    // ---------------------------------------------------------------- write helpers

    private int? Holder(Asset asset) => _openAssignments.TryGetValue(asset.Id, out var a) ? a.EmployeeId : null;

    private void History(Asset asset, AssetAction action, AssetStatus? previous, AssetStatus? next, int? employeeId, string? notes, DateTime at) =>
        db.AssetHistory.Add(new AssetHistory
        {
            AssetId = asset.Id, Action = action, PreviousStatus = previous, NewStatus = next, EmployeeId = employeeId,
            PerformedById = _adminId, Notes = notes, OccurredAt = at
        });

    private void Consume(Asset asset, InventoryTransactionType type, int quantity, int? assetId, int? employeeId, string notes, DateTime at)
    {
        _inStockPerItem[asset.InventoryItemId] = Math.Max(0, _inStockPerItem.GetValueOrDefault(asset.InventoryItemId) - 1);
        Txn(asset.InventoryItemId, type, quantity, assetId, employeeId, null, notes, at);
    }

    private void Restock(Asset asset, InventoryTransactionType type, int? employeeId, string notes, DateTime at)
    {
        _inStockPerItem[asset.InventoryItemId] = _inStockPerItem.GetValueOrDefault(asset.InventoryItemId) + 1;
        Txn(asset.InventoryItemId, type, 1, asset.Id, employeeId, null, notes, at);
    }

    private void ScrapRecordFor(Asset asset, string reason, DateTime at, bool wasInStock)
    {
        db.ScrapRecords.Add(new ScrapRecord
        {
            AssetId = asset.Id, ScrapDate = DateOnly.FromDateTime(at), Reason = reason, Quantity = 1,
            PerformedById = _adminId, CreatedAt = at, Notes = _rng.Next(0, 3) == 0 ? "Collected by the e-waste contractor." : null
        });
        if (wasInStock) _inStockPerItem[asset.InventoryItemId] = Math.Max(0, _inStockPerItem.GetValueOrDefault(asset.InventoryItemId) - 1);
        Txn(asset.InventoryItemId, InventoryTransactionType.Scrap, 1, asset.Id, null, null, reason, at);
    }

    private void Txn(int itemId, InventoryTransactionType type, int quantity, int? assetId, int? employeeId, int? _, string notes, DateTime at) =>
        db.InventoryTransactions.Add(new InventoryTransaction
        {
            InventoryItemId = itemId, Type = type, Quantity = quantity, BalanceAfter = _inStockPerItem.GetValueOrDefault(itemId),
            AssetId = assetId, EmployeeId = employeeId, Notes = notes, PerformedById = _adminId, OccurredAt = at
        });

    private void Activity(string action, string description, string entity, int? id, DateTime at, int? userId = null) =>
        db.ActivityLogs.Add(new ActivityLog
        {
            OccurredAt = at, UserId = userId ?? _adminId, UserEmail = _userEmails.GetValueOrDefault(userId ?? _adminId),
            Action = action, Entity = entity,
            EntityId = id?.ToString(), Description = description, IpAddress = "127.0.0.1", Result = ActivityResult.Success
        });

    // ---------------------------------------------------------------- random helpers

    private bool Chance(int percent) => _rng.Next(0, 100) < percent;

    private T? Pick<T>(IEnumerable<T> source)
    {
        var list = source as IList<T> ?? source.ToList();
        return list.Count == 0 ? default : list[_rng.Next(list.Count)];
    }

    private string[] Shuffle(string[] source) => source.OrderBy(_ => _rng.Next()).ToArray();
}
