    private readonly Dictionary<string, int> _tagCounters = new(StringComparer.OrdinalIgnoreCase);
    private readonly Dictionary<int, int> _inStockPerItem = [];
    private int _serialCounter;
    private int _requestCounter;
    private int _employeeCounter;

    private sealed record CatalogEntry(InventoryItem Item, decimal UnitCost, bool HasSerial, string[] Components);

    public async Task RunAsync(int days)
    {
        if (days <= 0) return;

        await LoadContextAsync();
        await CreateStaffAsync();

        var start = _today.AddDays(-(days - 1));
        logger.LogInformation("Simulating {Days} days of activity from {Start:yyyy-MM-dd}", days, start);

        // Open the period with a stock delivery so there is something to hand out on day one.
        await StockInAsync(start.AddHours(8), initial: true);

        for (var day = 0; day < days; day++)
        {
            var date = start.AddDays(day);
            for (var slot = 0; slot < EventsPerDay; slot++)
                await RunEventAsync(date, slot, day, days);
            await CommitDayAsync();
        }

        logger.LogInformation("Simulation complete: {Assets} assets, {Assignments} assignments, {History} history rows, {Requests} requests",
            await db.Assets.CountAsync(), await db.AssetAssignments.CountAsync(), await db.AssetHistory.CountAsync(), await db.Requests.CountAsync());
    }

