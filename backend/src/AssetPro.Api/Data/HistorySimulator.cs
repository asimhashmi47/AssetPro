/// <summary>
/// Builds a believable operating history on top of the deterministic demo data: for every day of the
/// last N months it performs about ten real operations (stock-ins, assignments, returns, repairs,
/// component replacements, scrapping and the request workflow), each writing the same history,
/// inventory and activity rows the API would write.
///
/// It only ever touches the staff and assets it creates itself, so the fixed demo scenarios the tests
/// rely on stay exactly as they are.
/// </summary>
public sealed class HistorySimulator(AppDbContext db, IPasswordHasher<User> hasher, ILogger logger)
{
    private const int EventsPerDay = 10;

    /// <summary>Days of history generated by default: a full six months ending today.</summary>
    public const int DefaultDays = 184;

    private readonly Random _rng = new(20261004);
    private readonly DateTime _today = DateTime.UtcNow.Date;

