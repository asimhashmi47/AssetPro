    private async Task RunEventAsync(DateTime date, int slot, int dayIndex, int totalDays)
    {
        // Business hours, in slot order, so a day reads naturally in the timeline.
        var at = date.AddHours(8.5 + slot * 0.9).AddMinutes(_rng.Next(0, 50));
        if (at > DateTime.UtcNow) at = DateTime.UtcNow.AddMinutes(-(EventsPerDay - slot));

        var weekend = date.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday;
        var ramping = dayIndex < totalDays * 0.15;
        foreach (var action in Shuffle(Weighted(ramping, weekend)))
        {
            if (await TryRunAsync(action, at)) return;
        }
        LogSignIn(at);
    }

    /// <summary>
    /// The pool an event is drawn from. Weekends keep the same ten events a day but lean towards the
    /// things that really happen then: employees raising requests and IT catching up on paperwork.
    /// </summary>
    private string[] Weighted(bool ramping, bool weekend) => (ramping, weekend) switch
    {
        (true, _) => ["assign", "assign", "assign", "stock-in", "request", "login", "replace", "assign", "repair-start"],
        (_, true) => ["request", "advance", "advance", "advance", "login", "login", "login", "replace", "repair-done", "retire"],
        _ => ["assign", "assign", "assign", "return", "return", "return", "request", "request",
              "advance", "advance", "advance", "advance", "advance", "repair-start", "repair-done",
              "replace", "replace", "stock-in", "stock-in", "damage", "release", "scrap", "retire", "login", "login"]
    };

    private async Task<bool> TryRunAsync(string action, DateTime at) => action switch
    {
        "stock-in" => await MaybeStockInAsync(at),
        "assign" => Assign(at),
        "return" => Return(at),
        "repair-start" => RepairStart(at),
        "repair-done" => RepairComplete(at),
        "replace" => ReplaceComponent(at),
        "damage" => MarkDamaged(at),
        "release" => ReleaseToStock(at),
        "retire" => Retire(at),
        "scrap" => Scrap(at),
        "request" => CreateRequest(at),
        "advance" => AdvanceRequest(at),
        _ => LogSignIn(at)
    };

    /// <summary>Saves the day and detaches the write-only rows, keeping the working set small.</summary>
    private async Task CommitDayAsync()
    {
        var newAssignments = db.ChangeTracker.Entries<AssetAssignment>()
            .Where(e => e.State == EntityState.Added).Select(e => e.Entity).ToList();

        await db.SaveChangesAsync();

        foreach (var assignment in newAssignments)
            _openAssignments[assignment.AssetId] = assignment;

        foreach (var entry in db.ChangeTracker.Entries().ToList())
        {
            var keep = entry.Entity switch
            {
                Asset asset => _assets.Contains(asset),
                AssetAssignment a => _openAssignments.TryGetValue(a.AssetId, out var open) && ReferenceEquals(open, a),
                AssetRequest r => _liveRequests.Contains(r),
                _ => false
            };
            if (!keep) entry.State = EntityState.Detached;
        }
    }

